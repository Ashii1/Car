export function calculateEffectiveStats(bike: OpenCityBike): OpenCityBikeStats {
  const stats: OpenCityBikeStats = { ...bike.baseStats };
  const u = bike.upgrades;

  stats.topSpeed += u.engine * UPGRADE_PRICING.engine.speedGain;
  stats.topSpeed += u.transmission * UPGRADE_PRICING.transmission.speedGain;
  stats.topSpeed += u.nitro * UPGRADE_PRICING.nitro.speedGain;

  stats.acceleration += u.engine * UPGRADE_PRICING.engine.accelGain;
  stats.acceleration += u.transmission * UPGRADE_PRICING.transmission.accelGain;
  stats.acceleration += u.nitro * UPGRADE_PRICING.nitro.accelGain;

  stats.handling += u.suspension * UPGRADE_PRICING.suspension.handlingGain;
  stats.handling += u.tires * UPGRADE_PRICING.tires.handlingGain;
  stats.handling += u.brakes * UPGRADE_PRICING.brakes.handlingGain;

  stats.braking += u.brakes * UPGRADE_PRICING.brakes.brakeGain;
  stats.braking += u.tires * UPGRADE_PRICING.tires.brakeGain;

  stats.offRoad += u.suspension * UPGRADE_PRICING.suspension.offRoadGain;

  stats.acceleration = Math.min(100, stats.acceleration);
  stats.handling = Math.min(100, stats.handling);
  stats.braking = Math.min(100, stats.braking);
  stats.offRoad = Math.min(100, stats.offRoad);

  // Upgrade Handling Profile
  const baseH = bike.handlingCharacteristics;
  if (baseH) {
    const effectiveAgility = Math.min(100, baseH.chassisAgility + u.suspension * 2 + u.tires * 2);
    const effectiveStability = Math.min(100, baseH.highSpeedStability + u.suspension * 2 + u.engine * 1);
    const effectiveLean = Math.min(68, Math.round(baseH.maxLeanAngle + u.suspension * 1.5 + u.tires * 1));
    const effectiveTurningRadius = Math.max(1.85, parseFloat((baseH.turningRadius - (u.suspension + u.tires) * 0.08).toFixed(2)));
    const effectiveThrottle = Math.min(100, baseH.throttleResponsiveness + u.transmission * 4 + u.engine * 2);

    stats.handlingCharacteristics = {
      ...baseH,
      chassisAgility: effectiveAgility,
      highSpeedStability: effectiveStability,
      maxLeanAngle: effectiveLean,
      turningRadius: effectiveTurningRadius,
      throttleResponsiveness: effectiveThrottle,
    };
  }

  return stats;
}
